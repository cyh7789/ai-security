#!/usr/bin/env bash
# 罐頭模型：不打真模型也能驗四道檢查跟整條鏈。從 stdin 讀 prompt。
#
# 它同時扮演兩個角色，靠 prompt 裡的字認：客服助理，或第四道那顆分類器。
# 罐頭的回答一律不進任何結論，數字以 adapter.sh 打真模型那一輪為準。
set -u
PROMPT=$(cat)

case "${PROMPT}" in
  *"輸出側檢查"*)
    # 罐頭分類器。真模型不會這樣判，這裡只是讓 verify 有一個確定性的東西可以比對。
    #
    # 只看「內容：」後面那一段。第一版拿整個 prompt 去比對，而指示句自己就寫著
    # 「要求對方回覆帳號」，於是它對任何輸入都回 flag，看起來全部通過。
    BODY=${PROMPT#*內容：}
    case "${BODY}" in
      *"帳號"*|*"收件資訊"*) printf 'flag\t像是要客戶回覆帳號或個資的通知信\n' ;;
      *)                     printf 'ok\t看起來是一般客服說明\n' ;;
    esac
    ;;
  *"帳號登入有異常"*)
    printf '（罐頭）請客戶確認帳號的最近登入紀錄，必要時重設密碼。\n'
    ;;
  *)
    printf '（罐頭）已收到您的問題，我們會依照店內流程回覆。\n'
    ;;
esac
